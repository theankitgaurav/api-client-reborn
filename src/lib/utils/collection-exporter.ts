import type { WorkspaceFileItem } from '../types';
import { getResolvedCommand } from './curl-generator.ts';

export interface FlattenedRequest {
  path: string;
  name: string;
  method: string;
  command: string;
  isGrpc: boolean;
}

/**
 * Recursively extracts all request files from a workspace folder item or item list.
 */
export function flattenWorkspaceRequests(
  items: WorkspaceFileItem[],
  readContentFn: (path: string) => string
): FlattenedRequest[] {
  const result: FlattenedRequest[] = [];

  for (const item of items) {
    if (item.is_dir && item.children) {
      result.push(...flattenWorkspaceRequests(item.children, readContentFn));
    } else if (!item.is_dir) {
      const rawContent = readContentFn(item.path);
      const isGrpc = item.name.endsWith('.grpcurl') || rawContent.trimStart().startsWith('grpcurl');
      result.push({
        path: item.path,
        name: item.display_name || item.name,
        method: item.method || (isGrpc ? 'gRPC' : 'GET'),
        command: rawContent,
        isGrpc,
      });
    }
  }

  return result;
}

/**
 * Generates a zero-dependency standalone POSIX shell script runner (`.sh`)
 * that sequentially executes requests, times their latency, prints colored
 * status badges, and aggregates test results in any terminal.
 */
export function generateCollectionShellScript(
  collectionName: string,
  requests: FlattenedRequest[],
  envVars: Record<string, string> = {}
): string {
  const lines: string[] = [];

  lines.push('#!/usr/bin/env bash');
  lines.push('# ==============================================================================');
  lines.push(`# Collection Runner: ${collectionName}`);
  lines.push(`# Generated by API Client Reborn - File-Native API Tool`);
  lines.push('# ==============================================================================');
  lines.push('');
  lines.push('set -u');
  lines.push('');
  lines.push('# Colors for terminal output');
  lines.push('RED="\\033[0;31m"');
  lines.push('GREEN="\\033[0;32m"');
  lines.push('BLUE="\\033[0;34m"');
  lines.push('YELLOW="\\033[1;33m"');
  lines.push('NC="\\033[0m" # No Color');
  lines.push('BOLD="\\033[1m"');
  lines.push('');

  // Default Environment Variables
  lines.push('# Environment Variables (override via CLI: e.g. base_url="https://prod" ./run.sh)');
  const varKeys = Object.keys(envVars);
  if (varKeys.length > 0) {
    for (const key of varKeys) {
      const val = envVars[key].replace(/"/g, '\\"');
      lines.push(`export ${key}="\${${key}:-"${val}"}"`);
    }
  } else {
    lines.push('# No default variables configured');
  }
  lines.push('');

  // Counters
  lines.push('TOTAL_REQUESTS=0');
  lines.push('PASSED_REQUESTS=0');
  lines.push('FAILED_REQUESTS=0');
  lines.push('');
  lines.push(`echo -e "\\n\${BOLD}\${BLUE}=======================================================\${NC}"`);
  lines.push(`echo -e "\${BOLD} Running Collection: ${collectionName}\${NC}"`);
  lines.push(`echo -e "\${BOLD}\${BLUE}=======================================================\${NC}\\n"`);
  lines.push('');

  // Iterate over each request
  requests.forEach((req, idx) => {
    const reqNum = idx + 1;
    const resolvedCmd = getResolvedCommand(req.command, envVars);

    lines.push(`# ------------------------------------------------------------------------------`);
    lines.push(`# Request #${reqNum}: ${req.name}`);
    lines.push(`# ------------------------------------------------------------------------------`);
    lines.push('TOTAL_REQUESTS=$((TOTAL_REQUESTS + 1))');
    lines.push(`echo -e "\\n\${BOLD}[${reqNum}/${requests.length}] ${req.method} \${NC}${req.name}"`);

    if (req.isGrpc) {
      // gRPC execution
      lines.push('START_TIME=$(date +%s%N 2>/dev/null || date +%s)');
      lines.push('RESPONSE_FILE=$(mktemp 2>/dev/null || mktemp -t api_client)');
      lines.push('ERROR_FILE=$(mktemp 2>/dev/null || mktemp -t api_client)');
      lines.push('');
      lines.push(`if ${resolvedCmd} > "$RESPONSE_FILE" 2> "$ERROR_FILE"; then`);
      lines.push('  END_TIME=$(date +%s%N 2>/dev/null || date +%s)');
      lines.push('  echo -e "  Status: ${GREEN}[gRPC OK]${NC}"');
      lines.push('  PASSED_REQUESTS=$((PASSED_REQUESTS + 1))');
      lines.push('else');
      lines.push('  echo -e "  Status: ${RED}[gRPC FAILED]${NC}"');
      lines.push('  cat "$ERROR_FILE"');
      lines.push('  FAILED_REQUESTS=$((FAILED_REQUESTS + 1))');
      lines.push('fi');
      lines.push('rm -f "$RESPONSE_FILE" "$ERROR_FILE"');
    } else {
      // cURL execution with status code and TTFB formatting
      lines.push('RESPONSE_FILE=$(mktemp 2>/dev/null || mktemp -t api_client)');
      lines.push('');
      // Wrap curl to write output and get HTTP status code
      lines.push(
        `HTTP_CODE=$(${resolvedCmd} -s -o "$RESPONSE_FILE" -w "%{http_code}" 2>/dev/null || echo "000")`
      );
      lines.push('if [ "$HTTP_CODE" -ge 200 ] && [ "$HTTP_CODE" -lt 400 ]; then');
      lines.push('  echo -e "  Status: ${GREEN}[HTTP $HTTP_CODE OK]${NC}"');
      lines.push('  PASSED_REQUESTS=$((PASSED_REQUESTS + 1))');
      lines.push('else');
      lines.push('  echo -e "  Status: ${RED}[HTTP $HTTP_CODE FAILED]${NC}"');
      lines.push('  FAILED_REQUESTS=$((FAILED_REQUESTS + 1))');
      lines.push('fi');
      lines.push('rm -f "$RESPONSE_FILE"');
    }
    lines.push('');
  });

  // Summary footer
  lines.push('# ==============================================================================');
  lines.push('# Final Summary');
  lines.push('# ==============================================================================');
  lines.push('echo -e "\\n${BOLD}-------------------------------------------------------${NC}"');
  lines.push('echo -e "${BOLD}Summary: ${TOTAL_REQUESTS} Total | ${GREEN}${PASSED_REQUESTS} Passed${NC} | ${RED}${FAILED_REQUESTS} Failed${NC}"');
  lines.push('echo -e "${BOLD}-------------------------------------------------------${NC}\\n"');
  lines.push('');
  lines.push('if [ "$FAILED_REQUESTS" -gt 0 ]; then');
  lines.push('  exit 1');
  lines.push('fi');
  lines.push('exit 0');

  return lines.join('\n');
}
