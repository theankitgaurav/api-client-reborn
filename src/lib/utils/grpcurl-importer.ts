import { createDefaultGrpcRequest } from './grpc.ts';
import type { GrpcRequestConfig } from '../types';

export interface GrpcurlImport {
  name: string;
  config: GrpcRequestConfig;
}

function shellTokens(command: string): string[] {
  const input = command.replace(/\\\r?\n/g, ' ');
  const tokens: string[] = [];
  let token = '';
  let quote: "'" | '"' | null = null;
  let escaped = false;
  let started = false;

  const flush = () => {
    if (started) tokens.push(token);
    token = '';
    started = false;
  };

  for (const char of input) {
    if (escaped) {
      token += char;
      started = true;
      escaped = false;
      continue;
    }
    if (quote === "'") {
      if (char === "'") quote = null;
      else token += char;
      started = true;
      continue;
    }
    if (quote === '"') {
      if (char === '"') quote = null;
      else if (char === '\\') escaped = true;
      else token += char;
      started = true;
      continue;
    }
    if (char === "'" || char === '"') {
      quote = char;
      started = true;
    } else if (char === '\\') {
      escaped = true;
      started = true;
    } else if (/\s/.test(char)) {
      flush();
    } else if (char === '|') {
      flush();
      tokens.push('|');
    } else {
      token += char;
      started = true;
    }
  }
  if (escaped || quote) throw new Error('The grpcurl command has an unfinished quote or escape.');
  flush();
  return tokens;
}

function isAbsolutePath(path: string): boolean {
  return path.startsWith('/') || /^[a-zA-Z]:[\\/]/.test(path);
}

function parseJsonBody(body: string, tokens: string[], grpcurlIndex: number): string {
  let value = body;
  if (body === '@') {
    const pipeIndex = tokens.lastIndexOf('|', grpcurlIndex);
    if (pipeIndex < 0 || tokens[0] !== 'printf') {
      throw new Error('Cannot import grpcurl -d @ unless JSON messages are piped with printf.');
    }
    const messageTokens = tokens.slice(2, pipeIndex);
    if (messageTokens.length === 0) throw new Error('The printf pipe contains no JSON messages.');
    try {
      value = JSON.stringify(messageTokens.map((message) => JSON.parse(message)), null, 2);
    } catch {
      throw new Error('The printf pipe must contain valid JSON messages.');
    }
  } else if (body.startsWith('@')) {
    throw new Error('Cannot import grpcurl data from a file; use inline JSON or a printf JSON pipe.');
  }

  try {
    return JSON.stringify(JSON.parse(value), null, 2);
  } catch {
    throw new Error('The grpcurl -d value must contain valid JSON.');
  }
}

/** Parse common grpcurl invocations, including commands generated by this app. */
export function parseGrpcurlCommand(command: string): GrpcurlImport {
  const tokens = shellTokens(command.trim());
  const grpcurlIndex = tokens.findLastIndex((token) => /(?:^|\/)grpcurl(?:\.exe)?$/i.test(token));
  if (grpcurlIndex < 0) throw new Error('No grpcurl command was found.');

  const config = createDefaultGrpcRequest();
  let plaintext = false;
  let insecure = false;
  let caFile: string | null = null;
  let protoFile: string | null = null;
  let importPath: string | null = null;
  let requestBody: string | null = null;
  const positionals: string[] = [];
  const args = tokens.slice(grpcurlIndex + 1);

  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    const equals = arg.indexOf('=');
    const option = equals > 0 ? arg.slice(0, equals) : arg;
    const inlineValue = equals > 0 ? arg.slice(equals + 1) : null;
    const takeValue = () => {
      const value = inlineValue ?? args[++index];
      if (value === undefined || value === '|') throw new Error(`Missing value for grpcurl option ${option}.`);
      return value;
    };

    switch (option) {
      case '-plaintext': plaintext = true; break;
      case '-insecure': insecure = true; break;
      case '-cacert': caFile = takeValue(); break;
      case '-proto': protoFile = takeValue(); break;
      case '-import-path': importPath = takeValue(); break;
      case '-d': requestBody = takeValue(); break;
      case '-H': {
        const header = takeValue();
        const colon = header.indexOf(':');
        if (colon < 1) throw new Error(`Invalid grpcurl metadata header: ${header}`);
        config.metadata.push({ key: header.slice(0, colon).trim(), value: header.slice(colon + 1).trim() });
        break;
      }
      default:
        if (arg.startsWith('-')) throw new Error(`Unsupported grpcurl option: ${option}`);
        positionals.push(arg);
    }
  }

  if (positionals.length !== 2) {
    throw new Error('A grpcurl command must include a target and a fully qualified service/method.');
  }
  if (plaintext && (insecure || caFile)) {
    throw new Error('grpcurl cannot combine -plaintext with TLS certificate options.');
  }
  if (insecure && caFile) throw new Error('grpcurl cannot combine -insecure with -cacert.');

  const target = positionals[0].replace(/^https?:\/\//i, '').replace(/\/$/, '');
  const methodPath = positionals[1];
  const slash = methodPath.lastIndexOf('/');
  if (slash < 1 || slash === methodPath.length - 1) {
    throw new Error('The grpcurl method must be written as package.Service/Method.');
  }

  const tlsEnabled = !plaintext;
  config.name = `gRPC ${methodPath.slice(slash + 1)}`;
  config.endpoint = `${tlsEnabled ? 'https' : 'http'}://${target}`;
  config.service = methodPath.slice(0, slash);
  config.method = methodPath.slice(slash + 1);
  config.tls_enabled = tlsEnabled;
  config.tls_insecure = insecure;
  config.tls_ca_file = caFile;
  config.proto_file = protoFile
    ? importPath && !isAbsolutePath(protoFile)
      ? `${importPath.replace(/[\\/]+$/, '')}/${protoFile.replace(/^[\\/]+/, '')}`
      : protoFile
    : null;
  config.use_reflection = !protoFile;
  config.request_json = requestBody === null ? '{}' : parseJsonBody(requestBody, tokens, grpcurlIndex);

  return { name: config.name, config };
}
